"""Lay out the `writer` cases for reading: each digest's request as the writer read it, then each
candidate's text and Gist. No model calls; reads the digests from the database the run read
(`fh_p1_sandbox`), as `litwatch eval ladders` does:

    LITWATCH_DATABASE_URL=<dev DSN for fh_p1_sandbox> uv run python \
        evals/2026-10-19-fallback-ladders/writer_pairs.py

It writes two files. writer-pairs.md names each candidate and ends with the key; writer-blind.md,
what the reader is given, labels them A, B and C in an order shuffled per digest with SEED.
"""

import asyncio
import random
from pathlib import Path

from litwatch import config, store
from litwatch.quality import ladders

HERE = Path(__file__).parent
SEED = 20261019


async def main() -> None:
    found = ladders.ladders(HERE / "ladders.toml")["writer"]
    chosen = [c for c in ladders.cases(HERE / "cases.csv") if c.role == "writer"]
    async with await store.connect(config.database_url()) as conn:
        built = await ladders.requests(conn, None, chosen)
        digests = {
            c.key: await (
                await conn.execute(
                    "SELECT topic, day FROM digests WHERE id = %s", (int(c.subject),)
                )
            ).fetchone()
            for c in chosen
        }
    last = ladders.latest(ladders.rows(HERE / "runs"))
    shuffle = random.Random(SEED)
    named, blind, key = [], [], []
    for c in chosen:
        d, request = digests[c.key], built[c.key]
        head = ["", f"## Digest {c.subject}: {d['topic']}, {d['day']}", "", "### Request", ""]
        head += ["```text", request.user if not isinstance(request, str) else request, "```"]
        named += head
        blind += head
        order = list(found.candidates)
        shuffle.shuffle(order)
        for letter, cand in zip("ABC", order, strict=True):
            r = last.get((c.key, cand.name))
            if r is None or r.output is None:
                said = [f"*{r.outcome if r else 'not asked'}*"]
            else:
                o = r.output
                said = [o["text"], "", f"**Gist.** {o['gist']}"]
                if o.get("picks"):
                    said += [
                        "",
                        "**Picks.** " + "; ".join(f"{p['paper']}: {p['why']}" for p in o["picks"]),
                    ]
            named += ["", f"### {cand.name} (`{cand.role.label}`)", "", *said]
            blind += ["", f"### Candidate {letter}", "", *said]
            key.append(f"| {c.subject} | {letter} | {cand.name} |")
    top = "Generated by writer_pairs.py from runs/writer.jsonl. Each digest's request is the one "
    top += "every candidate was sent."
    (HERE / "writer-pairs.md").write_text(
        "\n".join(
            [
                "# The `writer` cases, side by side",
                "",
                top,
                *named,
                "",
                "## Key to writer-blind.md",
                "",
                "| Digest | Letter | Candidate |",
                "|---|---|---|",
                *key,
            ]
        )  # fmt: skip
        + "\n"
    )
    (HERE / "writer-blind.md").write_text(
        "\n".join(["# Five digests, three writers each", "", top, *blind]) + "\n"
    )


if __name__ == "__main__":
    config.load_dotenv()
    asyncio.run(main())
