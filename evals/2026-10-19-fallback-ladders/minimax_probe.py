"""Why MiniMax M3.1 Flash (free) answered no call: one request to OpenRouter per parameter the
pipeline's requests carry (`openrouter.chat_request`: reasoning effort, a strict JSON schema with
`require_parameters`), alone and together, each reply's error or answer into minimax-probe.md.
The model is free; nothing is charged. Needs $OPENROUTER_API_KEY:

    uv run python evals/2026-10-19-fallback-ladders/minimax_probe.py
"""

import json
import os
from datetime import UTC, datetime
from pathlib import Path

import httpx

HERE = Path(__file__).parent
MODEL = "minimax/minimax-m3.1-flash:free"
SCHEMA = {
    "type": "json_schema",
    "json_schema": {
        "name": "Answer",
        "strict": True,
        "schema": {
            "type": "object",
            "properties": {"a": {"type": "string"}},
            "required": ["a"],
            "additionalProperties": False,
        },
    },
}
PROBES = {
    "plain": {},
    "reasoning effort high": {"reasoning": {"effort": "high"}},
    "require_parameters alone": {"provider": {"require_parameters": True}},
    "JSON schema, require_parameters": {
        "provider": {"require_parameters": True},
        "response_format": SCHEMA,
    },
    "JSON schema, require_parameters, reasoning high (the pipeline's)": {
        "provider": {"require_parameters": True},
        "response_format": SCHEMA,
        "reasoning": {"effort": "high"},
    },
}


def main() -> None:
    lines = [
        "# MiniMax M3.1 Flash (free), one request per parameter",
        "",
        f"Generated by minimax_probe.py on {datetime.now(UTC):%Y-%m-%d %H:%M} UTC.",
        "",
        "| Request | HTTP | Reply |",
        "| --- | --- | --- |",
    ]
    headers = {"Authorization": f"Bearer {os.environ['OPENROUTER_API_KEY']}"}
    with httpx.Client(base_url="https://openrouter.ai/api/v1", headers=headers, timeout=60) as c:
        for name, extra in PROBES.items():
            body = {
                "model": MODEL,
                "messages": [{"role": "user", "content": 'Answer {"a": "ok"} as JSON.'}],
                "max_tokens": 400,
            } | extra
            r = c.post("/chat/completions", json=body)
            reply = r.json()
            said = (reply.get("error") or {}).get("message") or json.dumps(
                reply["choices"][0]["message"]["content"]
            )
            lines.append(f"| {name} | {r.status_code} | {said.replace('|', '/')} |")
    (HERE / "minimax-probe.md").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
