/**
 * Writes the contracts the service shares with litwatch (`src/contracts.ts`) as one JSON Schema,
 * `contracts/deep.schema.json` at the repository's root: each contract a definition under `$defs`, and a schema
 * nested in one that is itself a contract a `$ref` to it, so litwatch's models get one class per contract
 * (`scripts/contracts.sh` generates them). CI fails when the committed file is stale.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { CONTRACTS } from "../src/contracts.ts";

// A schema as JSON, without TypeBox's own markers; equal JSON is the same schema.
const json = (schema: unknown): string => JSON.stringify(schema);
const named = new Map(Object.entries(CONTRACTS).map(([name, schema]) => [json(schema), name]));

/** The schema with every nested contract a reference; `self` is the contract it is. */
function referred(node: unknown, self?: string): unknown {
  if (Array.isArray(node)) return node.map((n) => referred(n));
  if (node === null || typeof node !== "object") return node;
  const name = named.get(json(node));
  if (name !== undefined && name !== self) return { $ref: `#/$defs/${name}` };
  return Object.fromEntries(Object.entries(node).map(([key, value]) => [key, referred(value)]));
}

const schema = {
  $schema: "https://json-schema.org/draft/2020-12/schema",
  $comment: "Generated by `npm run contracts` in deep/ from deep/src/contracts.ts; do not edit.",
  $defs: Object.fromEntries(Object.entries(CONTRACTS).map(([name, s]) => [name, referred(JSON.parse(json(s)), name)])),
};
const out = path.resolve(import.meta.dirname, "../../contracts/deep.schema.json");
mkdirSync(path.dirname(out), { recursive: true });
writeFileSync(out, `${JSON.stringify(schema, null, 2)}\n`);
console.log(`wrote ${out}`);
